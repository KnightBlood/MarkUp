/**
 * The shortcode that `before` ends with, or null.
 *
 * `before` is what precedes the caret, so this recognises `…:smile` at the moment
 * the *closing* colon is typed — that colon is the character being processed, so
 * it is not part of what came before.
 */
const SHORTCODE = /:([a-zA-Z0-9_+-]+)$/

export function shortcodeBefore(before: string): string | null {
  const match = SHORTCODE.exec(before)
  return match ? match[1]! : null
}

/** The emoji for a shortcode, or null when it is not one we know. */
export function emojiForShortcode(name: string): string | null {
  return EMOJI[name] ?? EMOJI[name.toLowerCase()] ?? null
}
